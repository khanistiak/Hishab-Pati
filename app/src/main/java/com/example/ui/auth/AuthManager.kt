import androidx.credentials.exceptions.GetCredentialInterruptedException
import androidx.credentials.exceptions.GetCredentialProviderConfigurationException
import androidx.credentials.exceptions.GetCredentialUnsupportedException
import androidx.credentials.exceptions.NoCredentialException
import com.example.R
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential.Companion.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
import com.google.firebase.Firebase
import com.google.firebase.FirebaseNetworkException
import com.google.firebase.auth.FirebaseAuthInvalidCredentialsException
import com.google.firebase.auth.FirebaseAuthInvalidUserException
import com.google.firebase.auth.FirebaseAuthUserCollisionException
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.NonCancellable
import kotlinx.coroutines.TimeoutCancellationException
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch
import kotlinx.coroutines.tasks.await
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeout
import java.util.concurrent.atomic.AtomicBoolean

object AuthManager {

    private val isSigningInProgress = AtomicBoolean(false)
    private val _isSigningInFlow = MutableStateFlow(false)
    val isSigningInFlow: StateFlow<Boolean> = _isSigningInFlow.asStateFlow()

    private const val FIREBASE_AUTH_TIMEOUT_MS = 30_000L

    private fun endSignInProgress() {
        isSigningInProgress.set(false)
        _isSigningInFlow.value = false
    }

    /**
     * Resolves the hosting Activity from a given Context (handling ContextWrapper / ComponentActivity).
     */
    fun findActivity(context: Context): Activity? {
        if (context is Activity) return context
        var current: Context? = context
        while (current is ContextWrapper) {
            if (current is Activity) return current
            current = current.baseContext
        }
        return null
    }

    const val FALLBACK_WEB_CLIENT_ID = "1070535347548-3q3ue02be4rj63qmsau99fgj770m0jdp.apps.googleusercontent.com"

    /**
     * Resolves the Web Client ID (client_type = 3) generated by the Google Services plugin
     * from app/google-services.json via R.string.default_web_client_id, with fallback to project constant.
     */
    fun getWebClientId(context: Context): String {
        val fromStringRes = try {
            val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
            if (resId != 0) {
                context.getString(resId).trim().takeIf {
                    it.isNotBlank() && !it.contains("example") && !it.contains("remixed")
                }
            } else {
                context.getString(R.string.default_web_client_id).trim().takeIf {
                    it.isNotBlank() && !it.contains("example") && !it.contains("remixed")
                }
            }
        } catch (e: Exception) {
            Log.w("Auth", "R.string.default_web_client_id lookup exception: ${e.message}, using fallback")
            null
        }
        return fromStringRes ?: FALLBACK_WEB_CLIENT_ID
    }

    /**
     * Checks whether a Credential Manager exception message indicates an OAuth / SHA-1
     * developer configuration mismatch (such as Play Services status 10 / [28444] when the
     * release APK signing certificate SHA-1 is not registered in Firebase Console).
     */
    internal fun isDeveloperConfigurationError(error: Throwable): Boolean {
        val combined = buildString {
            append(error.message.orEmpty())
            error.cause?.message?.let {
                append(' ')
                append(it)
            }
        }
        return combined.contains("28444") ||
            combined.contains("10:") ||
            combined.contains("16:") ||
            combined.contains("12500") ||
            combined.contains("DEVELOPER_ERROR", ignoreCase = true) ||
            combined.contains("Developer console is not set up correctly", ignoreCase = true) ||
            combined.contains("caller is not authorized", ignoreCase = true)
    }

    /**
     * Restores an existing persisted Firebase Authentication session on startup without
     * triggering unsolicited Credential Manager / passkey bottom-sheet requests.
     */
    fun attemptAutoSignIn(
        context: Context,
        credentialManager: CredentialManager,
        onAuthSuccess: () -> Unit,
        onUnauthenticated: () -> Unit,
        scope: CoroutineScope
    ) {
        val existingUser = try {
            Firebase.auth.currentUser
        } catch (e: Exception) {
            Log.w("Auth", "FirebaseAuth not ready during startup session check: ${e.message}")
            null
        }
        if (existingUser != null) {
            onAuthSuccess()
        } else {
            onUnauthenticated()
        }
    }

    fun onGoogleSignInClicked(
        context: Context,
        credentialManager: CredentialManager,
        onAuthSuccess: () -> Unit,
        onAuthError: (String) -> Unit,
        scope: CoroutineScope,
        onAuthCancelled: () -> Unit = {}
    ) {
        if (!isSigningInProgress.compareAndSet(false, true)) {
            Log.w("Auth", "Sign-in already in progress; ignoring duplicate trigger.")
            onAuthCancelled()
            return
        }
        _isSigningInFlow.value = true

        val clientId = getWebClientId(context)

        val activity = findActivity(context)
        if (activity == null || activity.isFinishing || activity.isDestroyed) {
            endSignInProgress()
            onAuthError("Unable to display sign-in: Activity window not available.")
            return
        }

        val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(signInOption)
            .build()

        val callbackDispatched = AtomicBoolean(false)
        val job = scope.launch {
            try {
                val result = credentialManager.getCredential(activity, request)
                val credential = result.credential
                if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                    val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                    if (googleIdToken.isBlank()) {
                        if (callbackDispatched.compareAndSet(false, true)) {
                            onAuthError("Authentication failed: Google returned an empty ID token.")
                        }
                        return@launch
                    }
                    val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                    withTimeout(FIREBASE_AUTH_TIMEOUT_MS) {
                        Firebase.auth.signInWithCredential(authCredential).await()
                    }
                    if (callbackDispatched.compareAndSet(false, true)) {
                        onAuthSuccess()
                    }
                } else {
                    if (callbackDispatched.compareAndSet(false, true)) {
                        onAuthError("Unexpected credential returned by Google Identity.")
                    }
                }
            } catch (e: TimeoutCancellationException) {
                Log.e("Auth", "Firebase signInWithCredential timed out", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("Sign-in timed out. Please check your internet connection and try again.")
                }
            } catch (e: kotlinx.coroutines.CancellationException) {
                Log.w("Auth", "Sign-in coroutine cancelled", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthCancelled()
                }
                throw e
            } catch (e: GetCredentialCancellationException) {
                Log.w("Auth", "Google Sign-In cancelled or dismissed: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    if (isDeveloperConfigurationError(e)) {
                        onAuthError(
                            "Google Sign-In failed (OAuth / SHA-1 mismatch). Ensure your release keystore SHA-1 and SHA-256 fingerprints are added to Firebase Console for com.istiak.hishabpati."
                        )
                    } else {
                        onAuthCancelled()
                    }
                }
            } catch (e: NoCredentialException) {
                Log.w("Auth", "No Google account found on device: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    if (isDeveloperConfigurationError(e)) {
                        onAuthError(
                            "Google Sign-In failed (OAuth / SHA-1 mismatch). Ensure your release keystore SHA-1 and SHA-256 fingerprints are added to Firebase Console for com.istiak.hishabpati."
                        )
                    } else {
                        onAuthError("No Google account found or authorized on this device. Please check your Google account in Android Settings.")
                    }
                }
            } catch (e: GetCredentialInterruptedException) {
                Log.w("Auth", "Google Sign-In was interrupted: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("Sign-in process was interrupted. Please try again.")
                }
            } catch (e: GetCredentialProviderConfigurationException) {
                Log.e("Auth", "Credential Manager provider configuration error: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("Google Play Services Credential Provider is unavailable or outdated on this device.")
                }
            } catch (e: GetCredentialUnsupportedException) {
                Log.e("Auth", "Credential Manager unsupported on device: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("Google Sign-In via Credential Manager is not supported on this device.")
                }
            } catch (e: GetCredentialCustomException) {
                Log.e("Auth", "Google Sign-In custom credential error (${e.type}): ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    if (isDeveloperConfigurationError(e)) {
                        onAuthError(
                            "Google Sign-In failed (OAuth / SHA-1 mismatch). Ensure your release keystore SHA-1 and SHA-256 fingerprints are added to Firebase Console for com.istiak.hishabpati."
                        )
                    } else {
                        onAuthError(e.localizedMessage ?: "Google Sign-In failed.")
                    }
                }
            } catch (e: GetCredentialException) {
                Log.e("Auth", "Credential Manager error (${e.type}): ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    if (isDeveloperConfigurationError(e)) {
                        onAuthError(
                            "Google Sign-In failed (OAuth / SHA-1 mismatch). Ensure your release keystore SHA-1 and SHA-256 fingerprints are added to Firebase Console for com.istiak.hishabpati."
                        )
                    } else {
                        onAuthError(e.localizedMessage ?: "Google Sign-In could not be completed.")
                    }
                }
            } catch (e: FirebaseNetworkException) {
                Log.e("Auth", "Firebase network failure: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("Network connection error. Please check your internet connection and try again.")
                }
            } catch (e: FirebaseAuthInvalidCredentialsException) {
                Log.e("Auth", "Invalid Firebase credentials: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("Authentication failed: invalid Google ID token.")
                }
            } catch (e: FirebaseAuthInvalidUserException) {
                Log.e("Auth", "User account invalid/disabled: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("This user account has been disabled or deleted.")
                }
            } catch (e: FirebaseAuthUserCollisionException) {
                Log.e("Auth", "Account collision: ${e.message}", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    onAuthError("An account already exists with a different credential.")
                }
            } catch (e: Exception) {
                Log.e("Auth", "Google Sign-In failed unexpectedly", e)
                if (callbackDispatched.compareAndSet(false, true)) {
                    if (isDeveloperConfigurationError(e)) {
                        onAuthError(
                            "Google Sign-In failed (OAuth / SHA-1 mismatch). Ensure your release keystore SHA-1 and SHA-256 fingerprints are added to Firebase Console for com.istiak.hishabpati."
                        )
                    } else {
                        onAuthError(e.localizedMessage ?: "Sign in failed. Please try again.")
                    }
                }
            } finally {
                endSignInProgress()
            }
        }
        job.invokeOnCompletion {
            endSignInProgress()
            if (callbackDispatched.compareAndSet(false, true)) {
                onAuthCancelled()
            }
        }
    }

    fun signOut(
        context: Context,
        credentialManager: CredentialManager,
        onSignOutComplete: () -> Unit,
        scope: CoroutineScope
    ) {
        scope.launch {
            withContext(NonCancellable) {
                try {
                    credentialManager.clearCredentialState(ClearCredentialStateRequest())
                } catch (e: Exception) {
                    Log.w("Auth", "Failed to clear credential state: ${e.message}", e)
                } finally {
                    Firebase.auth.signOut()
                    onSignOutComplete()
                }
            }
        }
    }
}

